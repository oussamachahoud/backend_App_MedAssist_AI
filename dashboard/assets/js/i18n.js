class DashboardI18n {
  constructor() {
    this.currentLang = localStorage.getItem('medassist_lang') || 'en';
    if (!['en', 'fr', 'ar'].includes(this.currentLang)) {
      this.currentLang = 'en';
    }
  }

  t(key, fallback = '') {
    const dict = DASHBOARD_TRANSLATIONS[this.currentLang] || DASHBOARD_TRANSLATIONS.en;
    return dict[key] || fallback || key;
  }

  init() {
    this.applyLanguage(this.currentLang);
    this.bindButtons();
  }

  setLanguage(lang) {
    if (!['en', 'fr', 'ar'].includes(lang)) return;
    this.currentLang = lang;
    try {
      localStorage.setItem('medassist_lang', lang);
    } catch (_) {}
    this.applyLanguage(lang, true);
  }

  applyLanguage(lang, triggerTabReload = false) {
    const isRtl = (lang === 'ar');
    document.documentElement.lang = lang;
    document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
    document.body.dir = isRtl ? 'rtl' : 'ltr';

    // Update active class on all lang buttons in DOM
    document.querySelectorAll('#dash-lang-en, #btnEn').forEach(b => b.classList.toggle('active', lang === 'en'));
    document.querySelectorAll('#dash-lang-fr, #btnFr').forEach(b => b.classList.toggle('active', lang === 'fr'));
    document.querySelectorAll('#dash-lang-ar, #btnAr').forEach(b => b.classList.toggle('active', lang === 'ar'));

    const dict = DASHBOARD_TRANSLATIONS[lang] || DASHBOARD_TRANSLATIONS.en;

    // 1. Text translations [data-i18n]
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    // 2. Placeholder translations [data-i18n-placeholder]
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) {
        el.setAttribute('placeholder', dict[key]);
      }
    });

    // 3. Title attribute translations [data-i18n-title]
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      if (dict[key]) {
        el.setAttribute('title', dict[key]);
      }
    });

    // 4. Update elements with inline data-en, data-fr, data-ar
    document.querySelectorAll('[data-en]').forEach(el => {
      const val = el.getAttribute(`data-${lang}`) || el.getAttribute('data-en');
      if (val) el.textContent = val;
    });

    // 5. Update dynamic header title/subtitle if helper exists
    if (typeof window.updateActiveTabHeaderTitle === 'function') {
      window.updateActiveTabHeaderTitle();
    }

    // 6. Notify active tab to reload/re-render charts with translated strings ONLY if explicitly requested
    if (triggerTabReload && typeof window.refreshActiveTabLanguage === 'function') {
      window.refreshActiveTabLanguage(lang);
    }
  }

  bindButtons() {
    document.querySelectorAll('#dash-lang-en, #btnEn').forEach(b => {
      b.onclick = () => this.setLanguage('en');
    });
    document.querySelectorAll('#dash-lang-fr, #btnFr').forEach(b => {
      b.onclick = () => this.setLanguage('fr');
    });
    document.querySelectorAll('#dash-lang-ar, #btnAr').forEach(b => {
      b.onclick = () => this.setLanguage('ar');
    });
  }
}

// Global i18n controller & quick translator helper
window.dashboardI18n = new DashboardI18n();
window.t = function(key, fallback = '') {
  return window.dashboardI18n ? window.dashboardI18n.t(key, fallback) : (fallback || key);
};

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => window.dashboardI18n.init());
} else {
  window.dashboardI18n.init();
}
